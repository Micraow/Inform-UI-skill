export function buildCases(input) {
  const edit=fn=>{const d=structuredClone(input);fn(d.body[0]);return d;},positives=[['original monthly supplied trends',structuredClone(input)]],negatives=[];
  const add=(n,fn)=>positives.push([n,edit(fn)]),bad=(n,fn,code='SCHEMA',path)=>negatives.push([n,edit(fn),code,path]);
  add('historical month with supplied previous reference',n=>{n.selectedMonth='month_june';n.comparison='previous';});
  add('explicit other month comparison',n=>{n.comparison='month_june';});
  add('missing exact comparison day remains unknown',n=>{n.averageSeries.points=n.averageSeries.points.filter(p=>p.day!==12);});
  add('unknown totals and empty points',n=>{n.months[0].totalValue=null;n.months[0].totalLabel=null;n.months[0].points=[];});
  add('provided future value remains unavailable in a current month',n=>{n.months[0].points.find(p=>p.day===18).value=999;n.months[0].points.find(p=>p.day===18).label='Supplied future observation';});
  add('masked private geometry',n=>{n.masked=true;n.maskedLabel='Hidden teaching value';});
  add('pending supplied trend',n=>{n.status='pending';});
  add('failed literal fallback',n=>{n.status='failed';n.fallback='<b>Supplied trend unavailable</b>';});
  add('no connected teaching account',n=>{n.hasConnectedAccounts=false;n.noAccountsLabel='No supplied teaching connection';});
  bad('missing category array',n=>{delete n.categories;});
  bad('empty month array',n=>{n.months=[];});
  bad('too many months',n=>{n.months=Array.from({length:25},(_,i)=>({...n.months[0],id:'month_'+i}));});
  bad('null resolution phase',n=>{n.status=null;});
  bad('duplicate supplied month ID',n=>{n.months[1].id=n.months[0].id;},'SPEND_MONTH_ID','/body/0/months/1/id');
  bad('reserved month ID',n=>{n.months[1].id='previous';},'SPEND_MONTH_ID','/body/0/months/1/id');
  bad('unknown selected month',n=>{n.selectedMonth='missing_month';},'SPEND_MONTH','/body/0/selectedMonth');
  bad('unknown comparison',n=>{n.comparison='missing_month';},'SPEND_COMPARISON','/body/0/comparison');
  bad('self comparison',n=>{n.comparison=n.selectedMonth;},'SPEND_COMPARISON','/body/0/comparison');
  bad('average needs supplied reference',n=>{delete n.averageSeries;},'SPEND_COMPARISON','/body/0/comparison');
  bad('current needs explicit elapsed days',n=>{delete n.months[0].daysElapsed;},'SPEND_DAY','/body/0/months/0/daysElapsed');
  bad('elapsed exceeds selected month length',n=>{n.months[0].dayCount=20;n.months[0].daysElapsed=21;},'SPEND_DAY','/body/0/months/0/daysElapsed');
  bad('duplicate day',n=>{n.months[0].points[1].day=n.months[0].points[0].day;},'SPEND_DAY','/body/0/months/0/points/1/day');
  bad('decreasing day',n=>{n.months[0].points[2].day=0;},'SPEND_DAY','/body/0/months/0/points/2/day');
  bad('point exceeds supplied day count',n=>{n.months[2].points.at(-1).day=31;},'SPEND_DAY','/body/0/months/2/points/4/day');
  bad('blank point display label',n=>{n.months[0].points[0].label=' ';},'SPEND_LABEL','/body/0/months/0/points/0/label');
  bad('day must be integer',n=>{n.months[0].points[0].day=1.5;});
  bad('point value must be numeric or null',n=>{n.months[0].points[0].value='0';});
  bad('missing explicit total label',n=>{delete n.months[0].totalLabel;});
  bad('account service endpoint is not supported',n=>{n.accountEndpoint='https://example.org/unrequested';});
  return{positives,negatives};
}
