export function buildCases(document) {
  const edit=fn=>{const next=structuredClone(document);fn(next.body[0],next.body[1]);return next;};
  const positives=[['original fictional schedule and ranking',structuredClone(document)]],negatives=[];
  const add=(name,fn)=>positives.push([name,edit(fn)]);
  const bad=(name,fn,code='SCHEMA',path)=>negatives.push([name,edit(fn),code,path]);
  add('empty supplied lists',(r,s)=>{r.races=[];s.standings=[];});
  add('race reader initially disabled',r=>{r.disabled=true;});
  add('session IDs scoped per race',r=>{r.races[1].sessions[0].id=r.races[0].sessions[0].id;});
  add('same round in different seasons',r=>{r.races[2].round=r.races[0].round;});
  add('unknown dates without fabricated ends',r=>{r.races[0].sessions[0].startsAt=null;delete r.races[0].sessions[0].endsAt;});
  add('supplied ties and unreconciled constructors',(_,s)=>{s.standings[2].rank=s.standings[0].rank;s.standings[6].points=999;});
  add('negative and fractional points',(_,s)=>{s.standings[0].points=-1000000;s.standings[1].points=0.125;s.standings[6].points=1000000;});
  add('literal text and explicit source',(r,s)=>{r.races[0].label='<img src=untrusted>';r.races[0].source={label:'Synthetic source',url:'https://example.org/weekend'};s.standings[0].note='<script>literal</script>';s.standings[0].source={label:'Synthetic rank',url:'https://example.org/rank'};});
  add('maximum finite lists',(r,s)=>{r.races=Array.from({length:80},(_,i)=>({...r.races[0],id:'race_'+i,round:i+1,sessions:Array.from({length:20},(_,j)=>({...r.races[0].sessions[0],id:'session_'+j}))}));s.standings=Array.from({length:100},(_,i)=>({...s.standings[0],id:'standing_'+i}));});
  bad('race provider endpoint',r=>{r.endpoint='https://example.org/live';});
  bad('standing calculation callback',(_,s)=>{s.calculatePoints='rule()';});
  bad('missing explicit unknown start',r=>{delete r.races[0].sessions[0].startsAt;});
  bad('local timestamp without offset',r=>{r.races[0].sessions[0].startsAt='2028-02-29T12:00';});
  bad('unknown session kind',r=>{r.races[0].sessions[0].kind='final';});
  bad('unknown supplied status',r=>{r.races[0].sessions[0].status='live';});
  bad('season outside bounds',r=>{r.races[0].season=1899;});
  bad('zero round',r=>{r.races[0].round=0;});
  bad('fractional round',r=>{r.races[0].round=1.5;});
  bad('excessive races',r=>{r.races=Array.from({length:81},(_,i)=>({...r.races[0],id:'r'+i,round:i+1}));});
  bad('excessive sessions',r=>{r.races[0].sessions=Array.from({length:21},(_,i)=>({...r.races[0].sessions[0],id:'s'+i}));});
  bad('excessive standings',(_,s)=>{s.standings=Array.from({length:101},(_,i)=>({...s.standings[0],id:'s'+i}));});
  bad('zero supplied rank',(_,s)=>{s.standings[0].rank=0;});
  bad('string points',(_,s)=>{s.standings[0].points='18.5';});
  bad('omitted unknown points',(_,s)=>{delete s.standings[0].points;});
  bad('negative wins',(_,s)=>{s.standings[0].wins=-1;});
  bad('duplicate race ID',r=>{r.races[1].id=r.races[0].id;},'DUPLICATE_ID','/body/0/races/1/id');
  bad('duplicate season and round',r=>{r.races[1].round=r.races[0].round;},'MOTORSPORT_ROUND','/body/0/races/1/round');
  bad('duplicate local session ID',r=>{r.races[0].sessions[1].id=r.races[0].sessions[0].id;},'DUPLICATE_ID','/body/0/races/0/sessions/1/id');
  bad('impossible session date',r=>{r.races[0].sessions[0].startsAt='2027-02-29T12:00Z';},'MOTORSPORT_TIME','/body/0/races/0/sessions/0/startsAt');
  bad('end without known start',r=>{r.races[0].sessions[0].startsAt=null;},'MOTORSPORT_INTERVAL','/body/0/races/0/sessions/0/endsAt');
  bad('equal normalized end',r=>{r.races[0].sessions[0].endsAt='2028-03-01T01:30Z';},'MOTORSPORT_INTERVAL','/body/0/races/0/sessions/0/endsAt');
  bad('duplicate standing ID',(_,s)=>{s.standings[1].id=s.standings[0].id;},'DUPLICATE_ID','/body/1/standings/1/id');
  bad('impossible observation',(_,s)=>{s.observedAt='2027-02-29T12:00Z';},'MOTORSPORT_TIME','/body/1/observedAt');
  bad('unsafe race source',r=>{r.races[0].source={label:'Unsafe',url:'javascript:run()'};},'UNSAFE_URL','/body/0/races/0/source/url');
  bad('relative ranking source',(_,s)=>{s.standings[0].source={label:'Relative',url:'/rank'};},'UNSAFE_URL','/body/1/standings/0/source/url');
  return {positives,negatives};
}
