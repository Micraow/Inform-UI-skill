export function buildCases(input){const positives=[],negatives=[],make=edit=>{const d=structuredClone(input);edit(d.body,d);return d;},pos=(n,f)=>positives.push([n,make(f)]),bad=(n,f,code='SCHEMA',path)=>negatives.push([n,make(f),code,path]);
 positives.push(['original three supplied views',structuredClone(input)]);
 pos('pending three views',(b,d)=>{d.body=b.map(n=>({type:n.type,label:n.label,status:'pending'}));});
 pos('failed literal fallbacks',(b,d)=>{d.body=b.map(n=>({type:n.type,label:n.label,status:'failed',fallback:'<b>Supplied unavailable text</b>'}));});
 pos('failed hidden views',(b,d)=>{d.body=b.map(n=>({type:n.type,label:n.label,status:'failed'}));});
 pos('resolved empty list and plan',b=>{b[1].items=[];delete b[1].viewAll;b[2].steps=[];});
 pos('unavailable steps remain null',b=>{b[2].steps=null;b[2].summaryErrorLabel='Supplied step data unavailable';});
 pos('mobile chat plan',b=>{b[2].mobile=true;});
 pos('library keeps original order',b=>{b[2].layout='library';});
 pos('language learning numbers unfinished steps',b=>{b[2].planType='language_learning';});
 pos('supplied initial disclosures',b=>{b[2].collapsed=true;b[2].completedExpanded=true;});
 pos('explicit global disabled',b=>{b.forEach(n=>n.disabled=true);});
 pos('item disabled independently',b=>{b[0].item.disabled=true;b[1].items[0].disabled=true;});
 bad('missing resolved item',b=>{delete b[0].item;});
 bad('pending forbids item',b=>{b[0].status='pending';});
 bad('failed forbids active list',b=>{b[1].status='failed';});
 bad('pending forbids steps',b=>{b[2].status='pending';});
 bad('unknown scheduling field',b=>{b[0].cron='* * * * *';});
 bad('blank accessible label',b=>{b[0].label=' ';},'AUTOMATION_DATA','/body/0/label');
 bad('blank schedule label',b=>{b[0].item.scheduleLabel=' ';},'AUTOMATION_DATA','/body/0/item/scheduleLabel');
 bad('unsafe item URL',b=>{b[0].item.url='javascript:alert(1)';},'AUTOMATION_DATA','/body/0/item/url');
 bad('duplicate list item',b=>{b[1].items[1].id=b[1].items[0].id;},'AUTOMATION_DATA','/body/1/items/1/id');
 bad('unsafe directory URL',b=>{b[1].viewAll.url='data:text/html,ignored';},'AUTOMATION_DATA','/body/1/viewAll/url');
 bad('list exceeds finite bound',b=>{b[1].items=Array.from({length:101},(_,i)=>({...b[1].items[0],id:`item_${i}`}));});
 bad('duplicate step',b=>{b[2].steps[1].id=b[2].steps[0].id;},'AUTOMATION_DATA','/body/2/steps/1/id');
 bad('unsupported step state',b=>{b[2].steps[0].status='scheduled';});
 bad('blank supplied state label',b=>{b[2].statusLabels.pending=' ';},'AUTOMATION_DATA','/body/2/statusLabels/pending');
 bad('null steps need error text',b=>{b[2].steps=null;},'AUTOMATION_DATA','/body/2/summaryErrorLabel');
 bad('collapse labels must pair',b=>{delete b[2].hidePlanLabel;},'AUTOMATION_DATA','/body/2/showPlanLabel');
 bad('collapsed library unsupported',b=>{b[2].layout='library';b[2].collapsed=true;},'AUTOMATION_DATA','/body/2/collapsed');
 bad('collapsed learning unsupported',b=>{b[2].planType='language_learning';b[2].collapsed=true;},'AUTOMATION_DATA','/body/2/collapsed');
 bad('blank step title',b=>{b[2].steps[0].title=' ';},'AUTOMATION_DATA','/body/2/steps/0/title');
 bad('long schedule label',b=>{b[0].item.scheduleLabel='x'.repeat(501);});
 bad('item ID contains whitespace',b=>{b[0].item.id='two words';});
 bad('disabled is literal boolean',b=>{b[0].disabled='true';});
 return{positives,negatives};}
